"""Issue #3: real Windows demonstration → corrected Skill → native verification.

An automated test driver performs a *real native mouse click* in a controlled
WinForms window while Piko's opt-in Teach hook and screenshot recorder are
active. It never claims the click was performed by a human or that an Ollama
model inferred a general purpose Skill. The user-reviewed plan then executes
through authenticated API routes with native UIA input and separate evidence.
"""
from __future__ import annotations

import asyncio
import os
import subprocess
import sys
from pathlib import Path

import httpx
import pytest

pytestmark = pytest.mark.skipif(
    sys.platform != "win32" or os.environ.get("PIKO_GUI_SMOKE") != "1",
    reason="Requires explicit interactive real Windows screenshot and input-hook testing",
)

ROOT = Path(__file__).resolve().parents[2]


class NoModelPlanner:
    async def close(self):
        pass

    async def plan(self, *_args, **_kwargs):
        raise AssertionError("A corrected Skill must not be regenerated by an LLM")


@pytest.mark.asyncio
async def test_native_demonstration_to_corrected_parameterized_skill(tmp_path):
    from pywinauto import Desktop

    from piko.api import create_app
    from piko.contracts import Expectation
    from piko.verification import verify
    from piko.windows import WindowsDesktop

    proc = subprocess.Popen(
        [
            "powershell.exe", "-NoProfile", "-ExecutionPolicy", "Bypass",
            "-File", str(ROOT / "examples/testbench.ps1"),
            "-Title", "Piko Teach E2E Testbench",
        ],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        creationflags=subprocess.CREATE_NEW_PROCESS_GROUP,
    )
    app = None
    try:
        win = Desktop(backend="uia").window(title="Piko Teach E2E Testbench")
        win.wait("visible enabled", timeout=30)
        win.set_focus()
        bridge = WindowsDesktop()
        observed = await asyncio.to_thread(bridge.observe)
        assert observed.window_title == "Piko Teach E2E Testbench"
        assert observed.process_id == proc.pid
        assert observed.window_handle is not None
        assert observed.process_started_at is not None

        token = "teach-smoke-" + "a" * 28
        app = create_app(
            token=token, reasoning_model="", desktop=bridge,
            inference=NoModelPlanner(), root=tmp_path,
        )
        auth = {"Authorization": "Bearer " + token}
        async with httpx.AsyncClient(
            transport=httpx.ASGITransport(app=app), base_url="http://test",
        ) as client:
            grant = await client.post("/permissions", headers=auth, json={
                "executable": observed.executable,
                "profile": "observe",
                "session_id": "teach",
            })
            assert grant.status_code == 200, grant.text
            start = await client.post(
                "/teach/start?seconds=12", headers=auth, json={
                    "executable": observed.executable,
                    "profile": "observe",
                    "session_id": "teach",
                },
            )
            assert start.status_code == 200, start.text
            demo_id = start.json()["id"]
            frame_path = tmp_path / "demonstrations" / demo_id / "frame-0000.png"
            for _ in range(120):
                if frame_path.is_file():
                    break
                await asyncio.sleep(0.05)
            assert frame_path.is_file(), "Live Windows screen was never captured"
            assert frame_path.stat().st_size > 100, "PNG must contain real image data"

            # This click is delivered via the OS pointer, not UIA.invoke().
            # The Pynput hook must therefore actually receive a permitted
            # structural click, with coordinates grounded in captured UIA.
            win.set_focus()
            await asyncio.sleep(0.25)
            win.child_window(auto_id="SaveButton", control_type="Button").click_input()
            for _ in range(120):
                recorder = app.state.teach
                if (recorder._event_queue.qsize() or any(
                    e.get("type") == "input.mouse_click" for e in recorder._events
                )):
                    break
                await asyncio.sleep(0.05)
            else:
                pytest.fail("Real Windows mouse hook did not capture the testbench click")

            stopped = await client.post("/teach/stop", headers=auth)
            assert stopped.status_code == 200, stopped.text
            assert stopped.json()["frames"] >= 1
            analysis_response = await client.get(
                f"/teach/{demo_id}/analysis", headers=auth,
            )
            assert analysis_response.status_code == 200, analysis_response.text
            analysis = analysis_response.json()
            assert analysis["input_events"] >= 1
            assert any(step["automation_id"] == "SaveButton"
                       for step in analysis["steps"]), analysis["steps"]

            # Raw typed text was never recorded. The reviewer explicitly adds
            # the missing text-entry action and its named value parameter.
            plan = {
                "objective": "Save a reviewed name in the controlled WinForms app",
                "explanation": "Set NameInput then press SaveButton; verify each outcome",
                "actions": [
                    {
                        "kind": "ui.set_text",
                        "automation_id": "NameInput",
                        "text": "{{person}}",
                        "expected": {
                            "automation_id": "NameInput",
                            "property": "text_equals", "value": "{{person}}",
                        },
                    },
                    {
                        "kind": "ui.click", "automation_id": "SaveButton",
                        "expected": {
                            "automation_id": "StatusLabel",
                            "property": "text_equals", "value": "Saved: {{person}}",
                        },
                    },
                ],
            }
            reject = await client.post(
                f"/teach/{demo_id}/draft", headers=auth, json={
                    "slug": "teach-native-save", "description": "Save a reviewed name",
                    "plan": plan, "confirmed_user_corrections": False,
                },
            )
            assert reject.status_code == 403
            saved = await client.post(
                f"/teach/{demo_id}/draft", headers=auth, json={
                    "slug": "teach-native-save", "description": "Save a reviewed name",
                    "plan": plan, "confirmed_user_corrections": True,
                },
            )
            assert saved.status_code == 200, saved.text
            assert saved.json()["status"] == "draft"
            assert saved.json()["verified"] is False

            win.set_focus()
            review = await client.post(
                "/skills/teach-native-save/review", headers=auth, json={
                    "authorize_foreground_app": True,
                    "parameters": {"person": "Ada"},
                },
            )
            assert review.status_code == 200, review.text
            session = review.json()
            assert session["state"] == "waiting_for_user"
            assert session["plan"]["actions"][0]["text"] == "Ada"
            approval = await client.post(
                f"/sessions/{session['id']}/execute", headers=auth,
            )
            assert approval.status_code == 200, approval.text
            for _ in range(160):
                current = (await client.get(
                    f"/sessions/{session['id']}", headers=auth,
                )).json()
                if current["state"] in {"completed", "failed", "cancelled"}:
                    break
                await asyncio.sleep(0.1)
            assert current["state"] == "completed", current.get("error")

            outcome = await asyncio.to_thread(bridge.observe)
            ok, reason = verify(Expectation(
                automation_id="StatusLabel", property="text_equals",
                value="Saved: Ada",
            ), outcome)
            assert ok, reason
            events = (await client.get(
                f"/sessions/{session['id']}/events", headers=auth,
            )).json()
            assert sum(event["type"] == "action.verified" for event in events) == 2
            assert "Ada" not in str([event["payload"] for event in events])
            for _ in range(100):
                history = (await client.get(
                    "/skills/teach-native-save/history", headers=auth,
                )).json()
                if history:
                    break
                await asyncio.sleep(0.05)
            assert len(history) == 1 and history[0]["completed"]
            assert history[0]["verified_actions"] == 2
            skill = (await client.get("/skills", headers=auth)).json()[0]
            assert skill["parameters"] == ["person"]
            assert skill["status"] == "draft", "Successful replay is not certification"
    finally:
        if app is not None:
            try:
                app.state.agent.emergency_stop()
                if app.state.teach.active_id is not None:
                    await app.state.teach.stop()
                app.state.agent.memory.close()
            except Exception:
                pass
        if proc.poll() is None:
            proc.terminate()
            try:
                proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                proc.kill()
